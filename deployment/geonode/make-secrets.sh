#!/usr/bin/env bash
#
# Creates deployment/geonode/secrets.env with random passwords for GeoNode.
#
# Runs once per machine and never overwrites an existing file: the GeoNode
# database volume keeps the passwords it was first initialised with, so new
# ones would lock GeoNode out of its own database. Back the file up together
# with the database.
#
# deploy.sh calls this automatically. On a dev machine run it once by hand:
#   bash deployment/geonode/make-secrets.sh

set -euo pipefail

SECRETS_FILE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/secrets.env"

if [[ -e "${SECRETS_FILE}" ]]; then
    echo "GeoNode secrets: ${SECRETS_FILE} already exists, keeping it"
    exit 0
fi

# Hex only: these end up inside URLs (DATABASE_URL) and env files.
rand() {
    od -An -N"${1:-24}" -tx1 /dev/urandom | tr -d ' \n'
}

postgres_password="$(rand)"
db_password="$(rand)"
geodb_password="$(rand)"

umask 077
cat > "${SECRETS_FILE}" <<EOF
# Generated by make-secrets.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Not in git.
# Do not edit the database passwords once GeoNode has started: the database
# keeps the ones it was created with.
POSTGRES_PASSWORD=${postgres_password}
GEONODE_DATABASE_PASSWORD=${db_password}
GEONODE_GEODATABASE_PASSWORD=${geodb_password}
DATABASE_URL=postgis://geonode:${db_password}@db:5432/geonode
GEODATABASE_URL=postgis://geonode_data:${geodb_password}@db:5432/geonode_data
GEOSERVER_ADMIN_PASSWORD=$(rand 16)
ADMIN_PASSWORD=$(rand 12)
OAUTH2_CLIENT_ID=$(rand 20)
OAUTH2_CLIENT_SECRET=$(rand 32)
SECRET_KEY=$(rand 32)
EOF

echo "GeoNode secrets: created ${SECRETS_FILE}"
echo "  GeoNode admin login: admin / see ADMIN_PASSWORD in that file"
